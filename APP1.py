def lesson_variables():
    st.header("1. 変数とデータ型 (データを入れる箱)")
    
    st.info("💡 **初心者向けのポイント: 変数は「箱」**\n\n"
            "プログラムでは、計算する数字や文字を一時的に保存しておく「箱」が必要です。この箱のことを**変数**と呼びます。\n"
            "C言語では、「この箱には整数しか入れない」「この箱には小数を入れる」というように、**箱の形（データ型）を最初に宣言する**という厳格なルールがあります。")
    
    st.subheader("代表的なデータ型（箱の種類）")
    st.markdown("""
    * **`int` (イント)**: 整数専用の箱。小数点のない数値を入れます（例: 10, -5, 100）
    * **`double` (ダブル)**: 小数・実数用の箱。細かい数値を扱います（例: 3.14, 22.5）
    * **`char` (キャラ)**: 文字専用の箱。アルファベット1文字などを入れます（例: 'A'）
    """)
    
    st.subheader("サンプルコード")
    st.code("""
#include <stdio.h> // 画面に文字を表示するための準備

int main(void) {
    // 1. 箱を用意して、中身を入れる（変数の宣言と代入）
    int age = 20;          // 整数用の箱「age」に 20 を入れる
    double height = 170.5; // 小数用の箱「height」に 170.5 を入れる
    
    // 2. 画面に表示する
    // %d は「ここに整数の箱の中身を入れるよ」という目印
    // %.1f は「ここに小数の箱の中身を、小数点第1位まで入れるよ」という目印
    printf("年齢は%d歳、身長は%.1fcmです。\\n", age, height);
    
    return 0; // プログラムを無事に終了する
}
    """, language="c")

    st.subheader("📝 確認クイズ")
    ans = st.radio("気温のような「小数」を含むデータを保存したい場合、どの箱（型）を用意すればよいですか？", 
                   ["選択してください", "int型", "double型", "char型"], key="q1")
    if ans == "double型":
        st.success("正解！小数を扱う場合は `double`（または `float`）を使用します。")
    elif ans != "選択してください":
        st.error("不正解です。intは整数、charは文字専用です。")

def lesson_control_flow():
    st.header("2. 制御構文 (条件分岐と繰り返し)")
    
    st.info("💡 **初心者向けのポイント: プログラムを自動化する魔法**\n\n"
            "プログラムが上から下へ順番に動くだけなら、電卓と同じです。状況に応じて動きを変える**「if文（もし〜なら）」**と、同じ作業を自動で繰り返す**「for文（〜回繰り返す）」**を使うことで、一気に便利になります。")
    
    st.subheader("サンプルコード: for文による繰り返し")
    st.write("for文は `for (スタート地点; ゴール地点; 歩幅)` という3つのルールを決めて動かします。")
    
    st.code("""
#include <stdio.h>

int main(void) {
    int i; // カウンター用の箱を用意
    
    // iを1からスタートし、5以下の間、iに1ずつ足しながら繰り返す
    // i++ は「i = i + 1」と同じ意味（インクリメント）
    for (i = 1; i <= 5; i++) {
        printf("%d回目の水やり\\n", i);
    }
    
    return 0;
}
    """, language="c")

    st.subheader("📝 確認クイズ")
    ans = st.radio("上記のコードで `i <= 5` を `i < 5` に変更した場合、画面に表示されるのは何回目までですか？", 
                   ["選択してください", "4回目", "5回目", "6回目"], key="q2")
    if ans == "4回目":
        st.success("正解！ `i < 5` は「5より小さい間」という意味になるため、iが4のときまでしか実行されません。")
    elif ans != "選択してください":
        st.error("不正解です。 `<`（より小さい）と `<=`（以下）の違いに注意しましょう。")

def lesson_pointers():
    st.header("3. ポインタ入門 (データの住所)")
    
    st.info("💡 **初心者向けのポイント: ポインタは「住所」**\n\n"
            "パソコンのメモリは、巨大なロッカーのようなものです。変数（箱）を作ると、そのロッカーのどこかの場所が割り当てられます。\n"
            "ポインタとは、箱の中身（データ）ではなく、**「その箱がロッカーの何番地にあるか（メモリアドレス）」**を記憶するための特別な変数です。")
    
    st.subheader("サンプルコード")
    st.code("""
#include <stdio.h>

int main(void) {
    int data = 100; // 普通の箱「data」に 100 を入れる
    int *ptr;       // 「住所」を記憶するための特別な箱（ポインタ変数）を宣言
    
    // & (アンパサンド) を変数名の前につけると、その変数の「住所」が分かる
    ptr = &data;    // dataの住所を ptr に記憶させる
    
    printf("dataの中身: %d\\n", data);
    printf("dataの住所: %p\\n", ptr); // %p は住所を表示する目印
    
    // * (アスタリスク) をポインタ変数の前につけると、「その住所にある箱の中身」を見に行ける
    printf("住所を頼りに中身を見る: %d\\n", *ptr);
    
    return 0;
}
    """, language="c")

    st.subheader("📝 確認クイズ")
    ans = st.radio("ある変数 `x` のメモリ上の住所（アドレス）を取得するための記号はどれですか？", 
                   ["選択してください", "*x", "&x", "%x"], key="q3")
    if ans == "&x":
        st.success("正解！ `&` は「アドレス演算子」と呼ばれ、変数の住所を取得します。")
    elif ans != "選択してください":
        st.error("不正解です。`*` は住所から中身を取り出すときに使います。")

def lesson_struct_file():
    st.header("4. 構造体とファイル入出力 (データの整理と保存)")
    
    st.info("💡 **初心者向けのポイント: 構造体は「バインダー」、ファイル保存は「ノートへの書き込み」**\n\n"
            "**構造体**: 品種名（文字）、栽培温度（小数）、収量（整数）など、バラバラの型の箱を1つのバインダーにまとめる機能です。\n"
            "**ファイル入出力**: プログラムが終了するとメモリ上のデータは消えてしまいます。それをCSVファイルなどの外部ノートに書き込んで永遠に残すための機能です。")

    st.subheader("サンプルコード")
    st.code("""
#include <stdio.h>
#include <string.h>

// 1. バインダーの設計図（構造体）を作る
struct CropData {
    char variety[20]; // 品種名（文字の集まり）
    double temp;      // 栽培温度（小数）
    int yield;        // 収量（整数）
};

int main(void) {
    // 2. 設計図をもとに「potato」というバインダーを作る
    struct CropData potato;
    
    // バインダーの中にデータを書き込む
    strcpy(potato.variety, "Koija"); // 文字列をセットする特別な命令
    potato.temp = 22.5;
    potato.yield = 150;
    
    // 3. データをCSVファイル（Excel等で開けるファイル）に保存する
    FILE *fp; // ファイルを操作するためのポインタ
    
    // "w" は Write（書き込み）モード。ファイルがなければ新しく作る
    fp = fopen("crop_data.csv", "w");
    
    if (fp == NULL) {
        printf("ファイルが開けません\\n");
        return 1; // エラー終了
    }
    
    // fprintf を使うと、画面ではなくファイルに文字を書き込める
    fprintf(fp, "Variety,Temperature,Yield\\n"); // 見出し
    fprintf(fp, "%s,%.1f,%d\\n", potato.variety, potato.temp, potato.yield); // データ
    
    fclose(fp); // ノートを閉じる（必ず必要！）
    printf("データをCSVに保存しました。\\n");
    
    return 0;
}
    """, language="c")

    st.subheader("📝 確認クイズ")
    ans = st.radio("既存のファイルの末尾にデータを「追記（付け足し）」したい場合、`fopen`のモードはどう指定しますか？", 
                   ["選択してください", "\"w\"", "\"r\"", "\"a\""], key="q4")
    if ans == "\"a\"":
        st.success("正解！ `a` は Append（追記）の略です。`w` だと以前のデータが消えて上書きされてしまいます。")
    elif ans != "選択してください":
        st.error("不正解です。`w`は新規書き込み（上書き）、`r`は読み込みです。")

def lesson_functions():
    st.header("5. 自作関数 (便利な機械を作る)")
    
    st.info("💡 **初心者向けのポイント: 関数は「自動販売機」**\n\n"
            "プログラムが長くなると見づらくなるため、よく使う計算や処理をまとめて一つの**「便利な機械（関数）」**を作ります。\n"
            "* **引数 (ひきすう):** 機械に入れる材料です。（例: 自動販売機に入れる「100円玉」）\n"
            "* **戻り値 (もどりち):** 機械から出てくる結果です。（例: 出てきた「缶ジュース」）")

    st.subheader("サンプルコード: 長方形の面積を計算する関数")
    st.code("""
#include <stdio.h>

// 1. 自作関数「calc_area」の設計
// 左端の int は「結果（戻り値）として整数を返すよ」という意味
// カッコの中身は「材料（引数）として整数の幅と高さをもらうよ」という意味
int calc_area(int width, int height) {
    int area = width * height; // 面積を計算
    return area;               // 計算結果（缶ジュース）を外に返す
}

int main(void) {
    int w = 5;
    int h = 10;
    int result;
    
    // 2. 自作関数を呼び出す
    // w と h を材料（100円玉）として渡すと、結果（缶ジュース）が result に入る
    result = calc_area(w, h);
    
    printf("幅%d、高さ%dの長方形の面積は %d です。\\n", w, h, result);
    
    return 0;
}
    """, language="c")

    st.subheader("📝 確認クイズ")
    ans = st.radio("関数の中で処理した結果を、関数の外（呼び出し元）に返すために使う英単語（キーワード）は何でしょうか？", 
                   ["選択してください", "send", "return", "output"], key="q5")
    if ans == "return":
        st.success("正解！ `return` を使うことで、計算した結果（戻り値）をメインの処理に引き渡すことができます。")
    elif ans != "選択してください":
        st.error("不正解です。コードの関数の中身をもう一度見てみましょう。")

